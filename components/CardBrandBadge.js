/**
 * Compact card-network badge (Stripe-style icons, same assets as the website).
 */
export default function CardBrandBadge({ brand, type, size = 'md', style }) {
  if (type === 'paypal' || normalizeCardBrand(brand) === 'paypal') {
    return (
      <View style={[styles.badge, size === 'sm' ? styles.badgeSm : styles.badgeMd, styles.paypal, style]}>
        <Text style={[styles.paypalText, size === 'sm' && styles.paypalTextSm]}>PayPal</Text>
      </View>
    );
  }

  const normalized = normalizeCardBrand(brand);
  const Icon = BRAND_ICONS[normalized];

  if (Icon) {
    return (
      <View
        style={[styles.badge, size === 'sm' ? styles.badgeSm : styles.badgeMd, styles.iconBadge, style]}
        accessibilityLabel={normalized === 'mastercard' || normalized === 'master' ? 'Mastercard' : normalized}
      >
        <View style={styles.iconInner}>
          <Icon />
        </View>
      </View>
    );
  }

  return (
    <View style={[styles.badge, size === 'sm' ? styles.badgeSm : styles.badgeMd, styles.fallback, style]}>
      <Text style={[styles.fallbackText, size === 'sm' && styles.fallbackTextSm]}>CARD</Text>
    </View>
  );
}

